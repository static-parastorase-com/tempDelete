    fun getPrediction(house: Int, language: JatakaLanguage): PredictionText {
        return when (language) {
            JatakaLanguage.HINDI -> getHindi(house)
            JatakaLanguage.KANNADA -> getKannada(house)
            JatakaLanguage.TAMIL -> getTamil(house)
            JatakaLanguage.MALAYALAM -> getMalayalam(house)
            JatakaLanguage.TELUGU -> getTelugu(house)
            else -> getEnglish(house)
        }
    }

